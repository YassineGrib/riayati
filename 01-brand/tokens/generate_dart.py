#!/usr/bin/env python3
"""Generate Flutter tokens from DTCG JSON. Run from any working directory.

References resolve recursively within their source file or via ../filename.
Dark semantics overlay light semantics; absent dark tokens inherit light values.
Does not import generate_tokens.py, whose import would rewrite brand sources.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = {n: json.loads((ROOT / f'{n}.json').read_text(encoding='utf-8'))
        for n in ('colors', 'typography', 'spacing', 'borders', 'shadows', 'motion')}


def leaves(node, prefix=()):
    for key, value in node.items():
        if key.startswith('$'):
            continue
        if '$value' in value:
            yield prefix + (key,), value['$value']
        else:
            yield from leaves(value, prefix + (key,))


def resolve(value, doc, seen=()):
    if isinstance(value, str) and value.startswith('{') and value.endswith('}'):
        ref = value[1:-1]
        if ref.startswith('../'):
            doc, ref = ref[3:].split('.', 1)
        identity = (doc, ref)
        if identity in seen:
            raise ValueError(f'Cyclic reference: {identity}')
        node = DOCS[doc]
        # Keys such as scale.2.5 contain a literal dot.
        while ref:
            key = next(k for k in sorted(node, key=len, reverse=True)
                       if ref == k or ref.startswith(k + '.'))
            node = node[key]
            ref = ref[len(key):].lstrip('.')
        return resolve(node['$value'], doc, seen + (identity,))
    if isinstance(value, dict):
        return {k: resolve(v, doc, seen) for k, v in value.items()}
    if isinstance(value, list):
        return [resolve(v, doc, seen) for v in value]
    return value


def name(parts):
    words = re.split(r'[-.]+', '-'.join(parts))
    result = words[0] + ''.join(w.title() for w in words[1:])
    return 'x' + result if result[0].isdigit() else result


def number(v):
    return str(float(re.sub(r'(px|em|ms)$', '', str(v))))


def color(v):
    if v.startswith('#'):
        return f'Color(0xFF{v[1:].upper()})'
    if v == 'transparent':
        return 'Color(0x00000000)'
    r, g, b, a = map(float, re.findall(r'[\d.]+', v))
    return f'Color.fromRGBO({int(r)}, {int(g)}, {int(b)}, {a})'


def generate():
    out = ["// GENERATED by 01-brand/tokens/generate_dart.py; do not edit.",
           "import 'package:flutter/material.dart';", "part 'riayati_colors.dart';"]
    semantic = dict(leaves(DOCS['colors']['semantic']))
    dark = dict(leaves(DOCS['colors']['dark']))
    fields = {p: name(p) for p in semantic}
    aliases = {'bg': 'surfacePage', 'surface': 'surfaceCard', 'primary': 'actionPrimary',
               'onPrimary': 'textOnAction', 'border': 'borderDefault', 'sos': 'sosBg',
               'sosSoft': 'sosBgSoft', 'success': 'feedbackSuccessIcon',
               'warning': 'feedbackWarningIcon'}
    out += ['abstract final class RColorTokens {']
    for mode in ('light', 'dark'):
        out += [f'static const {mode} = RColors(']
        for p, v in semantic.items():
            out += [f'{fields[p]}: {color(resolve(dark.get(p, v) if mode == "dark" else v, "colors"))},']
        out += [');']
    out += ['}']
    extension = ["part of 'tokens.g.dart';", '@immutable', 'class RColors extends ThemeExtension<RColors> {',
                 'const RColors({']
    extension += [f'required this.{f},' for f in fields.values()]
    extension += ['});'] + [f'final Color {f};' for f in fields.values()]
    extension += [f'Color get {a} => {f};' for a, f in aliases.items()]
    extension += ['static const light = RColorTokens.light;', 'static const dark = RColorTokens.dark;',
                  '@override', 'RColors copyWith({']
    extension += [f'Color? {f},' for f in fields.values()]
    extension += ['}) => RColors('] + [f'{f}: {f} ?? this.{f},' for f in fields.values()] + [');']
    extension += ['@override', 'RColors lerp(covariant RColors? other, double t) {',
                  'if (other == null) return this;', 'return RColors(']
    extension += [f'{f}: Color.lerp({f}, other.{f}, t)!,' for f in fields.values()]
    extension += [');', '}', '}', 'extension RiayatiColorContext on BuildContext {',
                  'RColors get c => Theme.of(this).extension<RColors>()!;', '}']
    # All generated data stays in tokens.g.dart; the extension is generated there too.
    out = out[:1] + ['// dart format off'] + out[1:2] + extension[1:] + out[3:]
    for cls, doc, groups in [('RSpace', 'spacing', ['scale', 'semantic']),
                             ('RRadius', 'borders', ['radius', 'radius-semantic']),
                             ('RBorderWidth', 'borders', ['width'])]:
        out += [f'abstract final class {cls} {{']
        for group in groups:
            for p, v in leaves(DOCS[doc][group]):
                field = 's' + '_'.join(p).replace('.', '_') if group == 'scale' else name(p)
                out += [f'static const double {field} = {number(resolve(v, doc))};']
        out += ['}']
    out += ['abstract final class RShadow {']
    for p, v in leaves(DOCS['shadows']):
        # Flutter BoxShadow has no inset rendering; retain the inset metadata.
        shadows = []
        for s in ([] if v == 'none' else v):
            shadows.append(f"BoxShadow(color: {color(s['color'])}, offset: Offset({number(s['offsetX'])}, {number(s['offsetY'])}), blurRadius: {number(s['blur'])}, spreadRadius: {number(s['spread'])})")
        field = name(p[1:] if p[0] == 'elevation' else p)
        expression = f'<BoxShadow>[{", ".join(shadows)}]'
        if p[0] == 'inner':
            expression = f'(inset: true, shadows: {expression})'
        out += [f'static const {field} = {expression};']
    out += ['}', 'abstract final class RMotion {']
    for p, v in leaves(DOCS['motion']):
        v = resolve(v, 'motion')
        field = name(p[1:] if p[0] in ('duration', 'easing') else p)
        if p[0] == 'duration' or p == ('reducedMotion', 'duration'):
            out += [f'static const {field} = Duration(milliseconds: {int(float(number(v)))});']
        elif p[0] == 'easing':
            out += [f'static const {field} = Cubic({", ".join(map(str, v))});']
        elif p[0] == 'transition':
            out += [f'static const {field} = (duration: Duration(milliseconds: {int(float(number(v["duration"])))}), curve: Cubic({", ".join(map(str, v["timingFunction"]))}), delay: Duration(milliseconds: {int(float(number(v["delay"])))}));']
    out += ['}', 'abstract final class RType {']
    families = {'thmanyah sans': 'ThmanyahSans', 'thmanyah serif display': 'ThmanyahSerifDisplay',
                'thmanyah serif text': 'ThmanyahSerifText', 'IBM Plex Sans Arabic': 'IBMPlexSansArabic'}
    for p, v in leaves(DOCS['typography']['textStyle']):
        v = resolve(v, 'typography')
        out += [f"static const {name(p)} = TextStyle(fontFamily: '{families[v['fontFamily'][0]]}', fontFamilyFallback: ['IBMPlexSansArabic'], fontSize: {number(v['fontSize'])}, fontWeight: FontWeight.w{v['fontWeight']}, height: {v['lineHeight']}, letterSpacing: {number(v['letterSpacing'])});"]
    out += ['}']
    target = ROOT.parents[1] / '03-app/mobile/lib/core/theme/tokens.g.dart'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(out) + '\n', encoding='utf-8')


if __name__ == '__main__':
    generate()
