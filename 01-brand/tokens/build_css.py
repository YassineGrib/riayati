#!/usr/bin/env python3
"""Build tokens.css (CSS custom properties) from the DTCG token files in this folder.

Aliases become var(--...) references, so the dark-mode override of a semantic token
cascades into every component token automatically.

Usage: python build_css.py [output.css]   (default: ./tokens.css)
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ALIAS = re.compile(r"\{([^}]+)\}")
FILES = ["colors", "typography", "spacing", "borders", "shadows", "sizing", "motion", "opacity", "breakpoints"]


def var_name(path, prefix=""):
    return "--" + (prefix + "-" if prefix else "") + "-".join(p.replace(".", "_") for p in path)


def to_css(value):
    if isinstance(value, list):
        return ", ".join(f'"{v}"' if " " in v else v for v in value)
    if isinstance(value, str):
        return ALIAS.sub(lambda m: "var(" + var_name(m.group(1).split(".")) + ")", value)
    return str(value)


def walk(node, path, out):
    if isinstance(node, dict):
        if "$value" in node:
            v = node["$value"]
            if isinstance(v, dict):  # composite (typography, shadow objects): skipped
                return
            if isinstance(v, list) and len(v) == 4 and all(isinstance(x, (int, float)) for x in v):
                out.append((path, "cubic-bezier(" + ", ".join(str(x) for x in v) + ")"))
                return
            if isinstance(v, list) and not all(isinstance(x, str) for x in v):
                return  # layered objects (shadows): skipped
            if isinstance(v, str) and v.strip().startswith("[") :
                return
            out.append((path, to_css(v)))
            return
        for k, child in node.items():
            if k.startswith("$"):
                continue
            walk(child, path + [k], out)


def main():
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "tokens.css"
    light, dark = [], []
    for name in FILES:
        f = HERE / f"{name}.json"
        if not f.exists():
            continue
        data = json.loads(f.read_text(encoding="utf-8"))
        if name == "colors":
            dk = data.pop("dark", None)
            walk(data, [], light)
            if dk:
                walk(dk, ["semantic"], dark)
        else:
            walk(data, [], light)
    lines = ["/* Generated by 01-brand/tokens/build_css.py. Do not edit by hand. */", ":root {"]
    lines += [f"  {var_name(p)}: {v};" for p, v in light]
    lines += ["}", "", ':root[data-theme="dark"] {', "  color-scheme: dark;"]
    lines += [f"  {var_name(p)}: {v};" for p, v in dark]
    lines += ["}", ""]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(light)} light vars, {len(dark)} dark overrides -> {out_path}")


if __name__ == "__main__":
    main()
